/**
 * sync-server.js — SAVERON Travel Local Sync Server
 * Run: node sync-server.js
 * Opens http://localhost:3000 and auto-writes JSON files on every admin save.
 */
const http = require('http');
const fs   = require('fs');
const path = require('path');

const PORT     = 3000;
const ROOT     = __dirname;
const DATA_DIR = path.join(ROOT, 'assets', 'data');

const MIME = {
  '.html':'text/html','.css':'text/css','.js':'application/javascript',
  '.json':'application/json','.png':'image/png','.jpg':'image/jpeg',
  '.jpeg':'image/jpeg','.gif':'image/gif','.svg':'image/svg+xml',
  '.ico':'image/x-icon','.woff':'font/woff','.woff2':'font/woff2',
  '.ttf':'font/ttf','.mp3':'audio/mpeg','.m4a':'audio/mp4',
  '.mp4':'video/mp4','.webp':'image/webp',
};

function readBody(req) {
  return new Promise((resolve, reject) => {
    let body = '';
    req.on('data', c => { body += c; });
    req.on('end', () => resolve(body));
    req.on('error', reject);
  });
}

function sendJSON(res, code, obj) {
  res.writeHead(code, {
    'Content-Type':'application/json',
    'Access-Control-Allow-Origin':'*',
    'Access-Control-Allow-Methods':'GET,POST,OPTIONS',
    'Access-Control-Allow-Headers':'Content-Type',
  });
  res.end(JSON.stringify(obj));
}

function serveStatic(res, fp) {
  fs.readFile(fp, (err, data) => {
    if (err) { res.writeHead(404); res.end('Not found'); return; }
    const mime = MIME[path.extname(fp).toLowerCase()] || 'application/octet-stream';
    res.writeHead(200, { 'Content-Type': mime, 'Cache-Control': 'no-cache' });
    res.end(data);
  });
}

async function handleSavePackages(req, res) {
  try {
    const data = JSON.parse(await readBody(req));
    if (!data || !Array.isArray(data.packages) || !Array.isArray(data.categories))
      return sendJSON(res, 400, { ok:false, error:'Invalid shape: needs {packages:[],categories:[]}' });

    const jsonStr = JSON.stringify(data, null, 2);
    const jsStr = `/**\n * packages-data.js — Auto-generated by SAVERON Admin\n * Last updated: ${new Date().toISOString()}\n */\nwindow.SAVERON_PACKAGES_DATA = ${jsonStr};\n`;

    fs.writeFileSync(path.join(DATA_DIR, 'packages.json'), jsonStr, 'utf8');
    fs.writeFileSync(path.join(DATA_DIR, 'packages-data.js'), jsStr, 'utf8');

    console.log(`[${new Date().toLocaleTimeString()}] Saved: ${data.packages.length} packages, ${data.categories.length} categories`);
    return sendJSON(res, 200, { ok:true, packages:data.packages.length, categories:data.categories.length, savedAt:new Date().toISOString() });
  } catch (e) {
    console.error('Save error:', e.message);
    return sendJSON(res, 500, { ok:false, error:e.message });
  }
}

async function handleSaveAdmin(req, res) {
  try {
    const creds = JSON.parse(await readBody(req));
    if (!creds || !creds.username || !creds.password)
      return sendJSON(res, 400, { ok:false, error:'Invalid credentials' });

    const jsonStr = JSON.stringify(creds, null, 2);
    const jsStr = `/**\n * admin-data.js — Auto-generated by SAVERON Admin\n * Last updated: ${new Date().toISOString()}\n */\nwindow.SAVERON_ADMIN_DATA = ${jsonStr};\n`;

    fs.writeFileSync(path.join(DATA_DIR, 'admin.json'), jsonStr, 'utf8');
    fs.writeFileSync(path.join(DATA_DIR, 'admin-data.js'), jsStr, 'utf8');

    console.log(`[${new Date().toLocaleTimeString()}] Saved: admin credentials`);
    return sendJSON(res, 200, { ok:true, savedAt:new Date().toISOString() });
  } catch (e) {
    console.error('Admin save error:', e.message);
    return sendJSON(res, 500, { ok:false, error:e.message });
  }
}

const server = http.createServer(async (req, res) => {
  const { method, url } = req;
  if (method === 'OPTIONS') {
    res.writeHead(204, { 'Access-Control-Allow-Origin':'*', 'Access-Control-Allow-Methods':'GET,POST,OPTIONS', 'Access-Control-Allow-Headers':'Content-Type' });
    res.end(); return;
  }
  if (method === 'POST' && url === '/api/save-packages') return handleSavePackages(req, res);
  if (method === 'POST' && url === '/api/save-admin')    return handleSaveAdmin(req, res);
  if (url === '/api/ping') return sendJSON(res, 200, { ok:true, server:'SAVERON Sync Server' });

  let fp = path.join(ROOT, url === '/' ? 'index.html' : url.split('?')[0]);
  if (fs.existsSync(fp) && fs.statSync(fp).isDirectory()) fp = path.join(fp, 'index.html');
  serveStatic(res, fp);
});

server.listen(PORT, '127.0.0.1', () => {
  console.log('');
  console.log('  SAVERON Travel – Local Sync Server');
  console.log('  -----------------------------------');
  console.log('  Website : http://localhost:' + PORT);
  console.log('  Admin   : http://localhost:' + PORT + '/adminlogin.html');
  console.log('  Saves   : Auto-writes to JSON files on disk!');
  console.log('  Stop    : Ctrl+C');
  console.log('');
});
